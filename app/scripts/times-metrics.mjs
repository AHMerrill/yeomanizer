// Regenerates src/format/timesMetrics.ts — the Adobe Core-14 Times advance widths (1/1000 em) for
// the WinAnsi character set, read from pdf-lib's bundled standard-font metrics. Tables autofit with
// these numbers so the preview, the PDF (which draws with these exact fonts), and the .docx all get
// the SAME column widths. Times New Roman is metric-compatible with Times, so Word and the browser
// lay the text out to the same widths.
//   node scripts/times-metrics.mjs
import { writeFileSync } from 'node:fs';
import { PDFDocument, StandardFonts } from 'pdf-lib';

const doc = await PDFDocument.create();
const fonts = {
  regular: await doc.embedFont(StandardFonts.TimesRoman),
  bold: await doc.embedFont(StandardFonts.TimesRomanBold),
  italic: await doc.embedFont(StandardFonts.TimesRomanItalic),
};
let chars = '';
for (let c = 0x20; c <= 0x7e; c++) chars += String.fromCharCode(c);
chars += '€‚ƒ„…†‡ˆ‰Š‹ŒŽ‘’“”•–—˜™š›œžŸ'; // WinAnsi 0x80–0x9F
for (let c = 0xa0; c <= 0xff; c++) chars += String.fromCharCode(c);
const widths = (f) => [...chars].map((ch) => Math.round(f.widthOfTextAtSize(ch, 1000)));
const row = (name, f) => `export const TIMES_${name}: readonly number[] = [${widths(f).join(',')}];\n`;

writeFileSync(
  new URL('../src/format/timesMetrics.ts', import.meta.url),
  `// GENERATED by scripts/times-metrics.mjs — do not edit by hand.
// Adobe Core-14 Times advance widths in 1/1000 em (via pdf-lib's standard-font metrics), indexed
// like TIMES_CHARS: printable ASCII, the WinAnsi 0x80–0x9F specials, then Latin-1 0xA0–0xFF.
export const TIMES_CHARS = ${JSON.stringify(chars)};
` +
    row('REGULAR', fonts.regular) +
    row('BOLD', fonts.bold) +
    row('ITALIC', fonts.italic),
);
console.log(`wrote ${[...chars].length} glyph widths × 3 faces`);
